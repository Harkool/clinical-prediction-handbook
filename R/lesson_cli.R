#!/usr/bin/env Rscript
if(.Platform$OS.type=="windows")
  invisible(Sys.setlocale("LC_CTYPE","English_United States.utf8"))
arguments <- commandArgs(trailingOnly=TRUE)
value <- function(name,default=NULL) {
  idx <- which(arguments==name)
  if(!length(idx)) return(default)
  if(length(idx)!=1L || idx==length(arguments)) stop("Missing/duplicate argument: ",name)
  arguments[idx+1L]
}
chapter <- value("--chapter","all"); mode <- value("--mode","quick")
if(!mode %in% c("quick","book")) stop("--mode must be quick or book")
script_arg <- grep("^--file=",commandArgs(trailingOnly=FALSE),value=TRUE)
if(length(script_arg)!=1L) stop("Execute this file with Rscript")
repo <- dirname(dirname(normalizePath(sub("^--file=","",script_arg),winslash="/",mustWork=TRUE)))
options(handbook.repo=repo)
output <- value("--output",file.path(repo,"outputs",mode))
for(module in c("core","interface","calibration","verify","development_intervals","competing_branch","course"))
  source(file.path(repo,"R",paste0(module,".R")),encoding="UTF-8")
verify_logic()
if(chapter!="all" && !grepl("^(0?[1-9]|1[0-9]|20)$",chapter))
  stop("--chapter must be all or an integer 1--20")
chapters <- if(chapter=="all") 1:20 else as.integer(chapter)
if(anyNA(chapters) || any(!chapters %in% 1:20)) stop("--chapter must be all or an integer 1--20")
for(ch in chapters) run_chapter(ch,output,mode)
cat("R_COURSE_SUCCESS chapters=",paste(chapters,collapse=",")," mode=",mode,"\n",sep="")
